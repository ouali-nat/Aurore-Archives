create table if not exists public.aurora_editorial_family_memory (
  id bigint generated by default as identity primary key,
  family_key text not null,
  version integer not null default 1 check (version > 0),
  title text not null,
  priority integer not null default 100,
  mandatory boolean not null default true,
  active boolean not null default true,
  content jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (family_key,version)
);

create unique index if not exists aurora_editorial_family_memory_active_uq
  on public.aurora_editorial_family_memory (family_key) where active;

alter table public.aurora_editorial_family_memory enable row level security;
revoke all on public.aurora_editorial_family_memory from public,anon,authenticated;
grant select on public.aurora_editorial_family_memory to service_role;

