create or replace function public.aurora_enforce_editorial_memory_gate()
returns trigger
language plpgsql
security invoker
set search_path=public,pg_temp
as $function$
declare
  v_session public.aurora_editorial_memory_sessions;
  v_session_id uuid;
  v_subject text;
  v_requires_math boolean;
  v_gate jsonb;
  v_expected jsonb;
  v_general_count integer;
  v_math_count integer;
  v_structure_count integer;
begin
  if coalesce(NEW.metadata->>'origin','') <> 'gpt_editorial_ingest' then return NEW; end if;
  if coalesce(NEW.metadata->>'memory_schema','') <> 'aurora-editorial-memory-3' then
    raise exception 'Memoire editoriale obligatoire : version de paquet memoire invalide';
  end if;
  v_gate:=coalesce(NEW.metadata->'editorial_memory_gate','{}'::jsonb);
  if coalesce(v_gate->>'read_confirmed','false')<>'true' or coalesce(v_gate->>'verified','false')<>'true' then
    raise exception 'Lecture obligatoire : les consignes editoriales doivent etre lues et attestees avant injection';
  end if;
  begin v_session_id:=nullif(trim(NEW.metadata->>'memory_session_id'),'')::uuid;
  exception when others then raise exception 'Memoire editoriale invalide : memory_session_id doit etre un UUID'; end;
  select * into v_session from public.aurora_editorial_memory_sessions
   where session_id=v_session_id and used_at is null and expires_at>now() for update;
  if not found then raise exception 'Memoire editoriale obligatoire : session absente, expiree ou deja consommee'; end if;
  if coalesce(v_session.metadata->>'memory_schema','')<>'aurora-editorial-memory-3' then
    raise exception 'Memoire editoriale obligatoire : session issue d’une ancienne version';
  end if;
  if nullif(trim(v_gate->>'session_id'),'') is distinct from v_session_id::text then raise exception 'Lecture obligatoire : session_id invalide'; end if;
  if nullif(trim(v_gate->>'bundle_sha256'),'') is distinct from v_session.bundle_sha256 then raise exception 'Lecture obligatoire : paquet memoire different'; end if;

  v_expected:=jsonb_build_object(
    'session_id',v_session.session_id::text,'bundle_sha256',v_session.bundle_sha256,
    'protocol_version',v_session.metadata #>> '{editorial_read_gate,protocol_version}',
    'protocol_sha256',v_session.metadata #>> '{editorial_read_gate,protocol_sha256}',
    'general_rule_keys',coalesce(v_session.metadata #> '{editorial_read_gate,general_rule_keys}','[]'::jsonb),
    'structure_rule_keys',coalesce(v_session.metadata #> '{editorial_read_gate,structure_rule_keys}','[]'::jsonb),
    'math_rule_keys',coalesce(v_session.metadata #> '{editorial_read_gate,math_rule_keys}','[]'::jsonb),
    'family_key',v_session.metadata #>> '{editorial_read_gate,family_key}',
    'family_version',nullif(v_session.metadata #>> '{editorial_read_gate,family_version}','')::int,
    'family_sha256',v_session.metadata #>> '{editorial_read_gate,family_sha256}',
    'subject_profile_key',v_session.metadata #>> '{editorial_read_gate,subject_profile_key}',
    'subject_profile_version',nullif(v_session.metadata #>> '{editorial_read_gate,subject_profile_version}','')::int,
    'subject_profile_sha256',v_session.metadata #>> '{editorial_read_gate,subject_profile_sha256}',
    'document_profile_key',v_session.metadata #>> '{editorial_read_gate,document_profile_key}',
    'document_profile_version',nullif(v_session.metadata #>> '{editorial_read_gate,document_profile_version}','')::int,
    'document_profile_sha256',v_session.metadata #>> '{editorial_read_gate,document_profile_sha256}'
  );

  if coalesce(v_gate->>'protocol_version','')<>coalesce(v_expected->>'protocol_version','')
  or coalesce(v_gate->>'protocol_sha256','')<>coalesce(v_expected->>'protocol_sha256','')
  or coalesce(v_gate->>'family_key','')<>coalesce(v_expected->>'family_key','')
  or coalesce(v_gate->>'family_version','')<>coalesce(v_expected->>'family_version','')
  or coalesce(v_gate->>'family_sha256','')<>coalesce(v_expected->>'family_sha256','')
  or coalesce(v_gate->>'document_profile_key','')<>coalesce(v_expected->>'document_profile_key','')
  or coalesce(v_gate->>'document_profile_version','')<>coalesce(v_expected->>'document_profile_version','')
  or coalesce(v_gate->>'document_profile_sha256','')<>coalesce(v_expected->>'document_profile_sha256','')
  or coalesce(v_gate->>'subject_profile_key','')<>coalesce(v_expected->>'subject_profile_key','')
  or coalesce(v_gate->>'subject_profile_version','')<>coalesce(v_expected->>'subject_profile_version','')
  or coalesce(v_gate->>'subject_profile_sha256','')<>coalesce(v_expected->>'subject_profile_sha256','') then
    raise exception 'Lecture obligatoire : une couche memoire de routage/profil ne correspond pas a la session';
  end if;

  if coalesce(v_gate->'general_rule_keys','[]'::jsonb)<>coalesce(v_expected->'general_rule_keys','[]'::jsonb)
  or coalesce(v_gate->'structure_rule_keys','[]'::jsonb)<>coalesce(v_expected->'structure_rule_keys','[]'::jsonb)
  or coalesce(v_gate->'math_rule_keys','[]'::jsonb)<>coalesce(v_expected->'math_rule_keys','[]'::jsonb) then
    raise exception 'Lecture obligatoire : liste des regles lues incomplete ou differente';
  end if;

  if nullif(trim(v_gate->>'ack_sha256'),'') is null
     or nullif(trim(v_gate->>'ack_sha256'),'') is distinct from (v_session.metadata #>> '{editorial_read_gate,ack_sha256}') then
    raise exception 'Lecture obligatoire : attestation cryptographique invalide';
  end if;

  v_subject:=lower(trim(coalesce(nullif(NEW.matiere,''),nullif(NEW.subject,''),'')));
  v_requires_math:=v_subject like '%math%';
  v_general_count:=coalesce(array_length(v_session.general_rule_ids,1),0);
  v_math_count:=coalesce(array_length(v_session.math_rule_ids,1),0);
  v_structure_count:=jsonb_array_length(coalesce(v_session.metadata #> '{editorial_read_gate,structure_rule_keys}','[]'::jsonb));
  if v_general_count<1 then raise exception 'Memoire editoriale obligatoire : pack general absent'; end if;
  if v_structure_count<1 then raise exception 'Memoire editoriale obligatoire : pack structure absent'; end if;
  if v_requires_math and (not v_session.requires_math or v_math_count<1) then raise exception 'Memoire mathematique obligatoire : pack absent'; end if;

  NEW.metadata:=coalesce(NEW.metadata,'{}'::jsonb)||jsonb_build_object('memory_gate',
    jsonb_build_object(
      'verified',true,'read_confirmed',true,'memory_schema','aurora-editorial-memory-3',
      'session_id',v_session.session_id,'retrieved_at',v_session.retrieved_at,'expires_at',v_session.expires_at,
      'general_rule_ids',to_jsonb(v_session.general_rule_ids),'math_rule_ids',to_jsonb(v_session.math_rule_ids),
      'general_memory_version',v_session.general_memory_version,'math_memory_version',v_session.math_memory_version,
      'bundle_sha256',v_session.bundle_sha256,'protocol_version',v_expected->>'protocol_version','protocol_sha256',v_expected->>'protocol_sha256',
      'general_rule_keys',v_expected->'general_rule_keys','structure_rule_keys',v_expected->'structure_rule_keys','math_rule_keys',v_expected->'math_rule_keys',
      'family_key',v_expected->>'family_key','family_version',v_expected->>'family_version','family_sha256',v_expected->>'family_sha256',
      'subject_profile_key',v_expected->>'subject_profile_key','subject_profile_version',v_expected->>'subject_profile_version','subject_profile_sha256',v_expected->>'subject_profile_sha256',
      'document_profile_key',v_expected->>'document_profile_key','document_profile_version',v_expected->>'document_profile_version','document_profile_sha256',v_expected->>'document_profile_sha256',
      'ack_sha256',v_session.metadata #>> '{editorial_read_gate,ack_sha256}'
    ));
  return NEW;
end;
$function$;
